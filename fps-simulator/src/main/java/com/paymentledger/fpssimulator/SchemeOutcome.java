package com.paymentledger.fpssimulator;

import java.util.Objects;
import org.jspecify.annotations.Nullable;

/**
 * The scheme's final answer to a Scheme Submission: accepted (ACSC), or rejected (RJCT) with an ISO
 * 20022 reason code.
 */
record SchemeOutcome(Status status, @Nullable ReasonCode reasonCode) {

  static final SchemeOutcome ACCEPTED = new SchemeOutcome(Status.ACSC, null);

  SchemeOutcome {
    Objects.requireNonNull(status, "status");
    if ((status == Status.RJCT) != (reasonCode != null)) {
      throw new IllegalArgumentException(
          "A rejected Scheme Outcome, and only one, has a reason code");
    }
  }

  static SchemeOutcome rejected(ReasonCode reasonCode) {
    return new SchemeOutcome(Status.RJCT, reasonCode);
  }

  enum Status {
    ACSC,
    RJCT
  }

  /** The reason codes the scheme gives with a Scheme Rejection. */
  enum ReasonCode {
    /** Incorrect account number. */
    AC01,
    /** Closed account number. */
    AC04,
    /** Transaction forbidden on this type of account. */
    AG01,
    /** Not specified reason, generated by the agent. */
    MS03
  }
}
